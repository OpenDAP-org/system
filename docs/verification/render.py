"""Renders primitives-matrix.toml into primitives-matrix.md: the coverage by area and status, then
every case, area by area. Checks the data first (unique ids, known statuses, every field filled), so
a bad row fails here rather than in a reader's eyes. `--check` exits 1 when the markdown is stale."""

import sys
import tomllib
from collections import Counter, OrderedDict
from pathlib import Path

HERE = Path(__file__).parent
STATUSES = OrderedDict(
    verified="verified in the running product (virtual T1)",
    unit="tests only, with the reason",
    gap="found and open",
    open="not tried yet",
    blocked="cannot be produced here, with the reason",
    na="does not apply",
)
FIELDS = ["id", "area", "primitive", "conditions", "case", "expected", "observed", "evidence", "status", "date"]


def load():
    cases = tomllib.loads((HERE / "primitives-matrix.toml").read_text())["case"]
    seen = set()
    for c in cases:
        missing = [f for f in FIELDS if f not in c or (f != "conditions" and not str(c[f]).strip())]
        if missing:
            sys.exit(f"{c.get('id', '?')}: missing {', '.join(missing)}")
        if c["id"] in seen:
            sys.exit(f"{c['id']}: duplicate id")
        if c["status"] not in STATUSES:
            sys.exit(f"{c['id']}: unknown status {c['status']}")
        seen.add(c["id"])
    return cases


def cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def render(cases):
    areas = list(OrderedDict.fromkeys(c["area"] for c in cases))
    count = Counter((c["area"], c["status"]) for c in cases)
    total = Counter(c["status"] for c in cases)
    out = [
        "<!-- Generated by render.py from primitives-matrix.toml: edit the data, then run it. -->",
        "",
        "# The composer's primitives: combinatorial matrix",
        "",
        "Every combination of a primitive with the conditions it meets (input source, focus shown or hidden, right to left, reduce motion, disabled, the blueprint, the display off, reduce transparency) that makes sense together, one case per row, with what was expected, what was seen and where the evidence is. Kept up to date as cases are tried (the composer and UI runtime spec's verification; the global definition of done: verified in the running product).",
        "",
        "**Status:** " + " · ".join(f"*{k}*: {v}" for k, v in STATUSES.items()) + ".",
        "",
        "## Coverage",
        "",
        "| Area | " + " | ".join(STATUSES) + " | Cases |",
        "|---|" + "---|" * (len(STATUSES) + 1),
    ]
    for a in areas:
        n = sum(count[(a, s)] for s in STATUSES)
        out.append(f"| {a} | " + " | ".join(str(count[(a, s)] or "") for s in STATUSES) + f" | {n} |")
    out.append("| **All** | " + " | ".join(f"**{total[s]}**" for s in STATUSES) + f" | **{len(cases)}** |")
    for a in areas:
        out += ["", f"## {a[0].upper() + a[1:]}", "", "| Id | Primitive | Conditions | Case | Expected | Observed | Evidence | Status |", "|---|---|---|---|---|---|---|---|"]
        for c in (c for c in cases if c["area"] == a):
            conds = ", ".join(c["conditions"]) or "—"
            out.append("| " + " | ".join(cell(x) for x in [c["id"], c["primitive"], conds, c["case"], c["expected"], c["observed"], c["evidence"], f"{c['status']} ({c['date']})"]) + " |")
    return "\n".join(out) + "\n"


def main():
    md = render(load())
    target = HERE / "primitives-matrix.md"
    if "--check" in sys.argv:
        sys.exit(0 if target.exists() and target.read_text() == md else 1)
    target.write_text(md)


if __name__ == "__main__":
    main()
